# 3. GRID RELIABILITY ANALYTICS (fig10_grid_reliability.pdf)
# ==============================================================================
def build_grid_reliability_figure(df_raw):
    fig, axes = plt.subplots(1, 2, figsize=(11.2, 3.9))

    ax = axes[0]
    loss = (df_raw["Max. Demand at eve. peak (Generation end)"] - df_raw["Max. Demand at eve. peak (Sub-station end)"]).dropna()
    loss_roll = loss.rolling(30).mean()
    ax.plot(loss.index, loss.values, color="#9ca3af", alpha=0.35, lw=0.6, label="Daily Peak Loss")
    ax.plot(loss_roll.index, loss_roll.values, color="#9b2226", lw=1.6, label="30-Day Moving Average")
    ax.axhline(loss.mean(), color="#1d3557", ls="--", lw=1.2, label=f"Mean: {loss.mean():.2f} MW")
    ax.set_ylabel("Peak Transmission Loss (MW)")
    ax.set_title("(a) National Peak Transmission System Loss (2019–2026)")
    ax.grid(alpha=0.25)
    ax.legend(fontsize=7.5)

    ax = axes[1]
    divs = ["Dhaka", "Chattogram", "Rajshahi", "Khulna", "Mymensingh", "Rangpur", "Barishal", "Sylhet"]
    deficits = [(df_raw[f"{d}_supply"] - df_raw[f"{d}_demand"]).mean() for d in divs]
    s_def = pd.Series(deficits, index=divs).sort_values()
    c_def = ["#d62828" if v < 0 else "#2a9d8f" for v in s_def.values]
    ax.barh(s_def.index, s_def.values, color=c_def)
    ax.axvline(0, color="black", lw=0.9)
    for i, v in enumerate(s_def.values):
        ax.text(v - 1.5 if v < 0 else v + 1.5, i, f"{v:.1f}", va="center",
                ha="right" if v < 0 else "left", fontsize=7.8)
    ax.set_xlim(-47, max(12, s_def.max() + 8))
    ax.set_xlabel("Mean Net Supply Balance: Supply − Demand (MW)")
    ax.set_title("(b) Structural Regional Supply Deficits (8 Divisions)")
    ax.grid(axis="x", alpha=0.25)

    fig.tight_layout()
    fig.savefig(f"{FIG_DIR}/fig10_grid_reliability.pdf")
    plt.close(fig)
    print("Saved fig10_grid_reliability.pdf")


