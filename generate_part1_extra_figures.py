# 2. STRICTLY CAUSAL TREESHAP SURROGATE ATTRIBUTION (fig9_shap_attribution.pdf)
# ==============================================================================
def build_causal_shap_figure(df_raw):
    target_col = "Max. Demand at eve. peak (Generation end)"
    df = df_raw.copy()
    # Strictly lagged (t-1) meteorological & demand features — ZERO same-day look-ahead
    t_lag1 = df["Maximum Temperature in Dhaka was"].shift(1)
    df["Temp_Lag1"] = t_lag1
    df["CDD_Lag1"] = t_lag1.apply(lambda t: max(0.0, t - 24.0) if pd.notna(t) else np.nan)
    df["HDD_Lag1"] = t_lag1.apply(lambda t: max(0.0, 18.0 - t) if pd.notna(t) else np.nan)

    ys = df[target_col].shift(1)
    df["Demand_Lag1"] = ys
    df["Roll_Mean_7d"] = ys.rolling(7).mean()
    df["Roll_Mean_14d"] = ys.rolling(14).mean()
    df["Roll_Max_7d"] = ys.rolling(7).max()
    df["Demand_Diff_1d"] = ys - df[target_col].shift(2)

    # Deterministic public holiday calendar indicators known in advance
    df["Holiday_Flag"] = (df["Holiday_cat"] > 0).astype(float)
    df["Eid_Lead_1"] = (df["Holiday_cat"].shift(-1).fillna(0) > 0).astype(float)
    df["Eid_Lag_1"] = (df["Holiday_cat"].shift(1).fillna(0) > 0).astype(float)
    df["Is_Weekend"] = df["Day of the week"].isin(["Friday", "Saturday"]).astype(float)

    shap_feats = [
        "Demand_Lag1", "Roll_Mean_7d", "Roll_Mean_14d", "Roll_Max_7d", "Demand_Diff_1d",
        "CDD_Lag1", "HDD_Lag1", "Temp_Lag1", "Holiday_Flag", "Eid_Lead_1",
        "Eid_Lag_1", "Is_Weekend", "Month"
    ]
    df_sh = df[shap_feats + [target_col]].dropna()
    tr_cut = int(0.70 * len(df_sh))
    va_cut = int(0.80 * len(df_sh))

    # Fit surrogate strictly on 70% training split (with val early stopping), evaluate on 462-day blind test set
    xm_tab = xgb.XGBRegressor(
        n_estimators=400, max_depth=4, learning_rate=0.05,
        early_stopping_rounds=10, eval_metric="mae", random_state=42, n_jobs=1
    )
    xm_tab.fit(
        df_sh[shap_feats].iloc[:tr_cut], df_sh[target_col].iloc[:tr_cut],
        eval_set=[(df_sh[shap_feats].iloc[tr_cut:va_cut], df_sh[target_col].iloc[tr_cut:va_cut])],
        verbose=False,
    )
    expl = shap.TreeExplainer(xm_tab)
    sv = expl.shap_values(df_sh[shap_feats].iloc[va_cut + 14 :])
    mean_shap = pd.Series(np.abs(sv).mean(axis=0), index=shap_feats).sort_values(ascending=True)
    mean_shap.sort_values(ascending=False).to_csv(f"{OUT_DIR}/part1_causal_shap.csv", header=["Mean_Abs_SHAP_MW"])
    print("\nStrictly Causal TreeSHAP Surrogate (Train-Only 70%, Blind Test N =", len(sv), "):")
    print(mean_shap.sort_values(ascending=False).round(1).to_string())

    fig, ax = plt.subplots(figsize=(8.2, 4.1))
    ax.barh(mean_shap.index, mean_shap.values, color="#2a9d8f")
    for i, v in enumerate(mean_shap.values):
        ax.text(v + 8, i, f"{v:.1f} MW", va="center", fontsize=7.8)
    ax.set_xlabel("Mean |SHAP Value| on 462-Day Blind Test Set (MW)")
    ax.set_title("Strictly Causal TreeSHAP Surrogate Attribution (Past-Only Lags, Train-Only Fit)")
    ax.set_xlim(0, mean_shap.max() * 1.18)
    ax.grid(axis="x", alpha=0.25)
    fig.tight_layout()
    fig.savefig(f"{FIG_DIR}/fig9_shap_attribution.pdf")
    plt.close(fig)
    print("Saved fig9_shap_attribution.pdf")


